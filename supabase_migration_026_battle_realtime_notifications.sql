drop trigger if exists notify_battle_ready_change on public.battle_round_ready;
create trigger notify_battle_ready_change
after insert or update on public.battle_round_ready
for each row execute function public.notify_battle_ready_change();

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'battle_realtime_events'
  ) then
    alter publication supabase_realtime add table public.battle_realtime_events;
  end if;
end;
$$;

commit;
