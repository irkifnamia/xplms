create or replace function public.current_role() returns text
language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

-- All XP balance changes flow through this trigger. Clients never update
-- stud_xp directly.
create or replace function public.apply_xp_event() returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.stud_xp
  set "XP" = coalesce("XP", 0) + new.points,
      updated_at = now()
  where "NO MATRIK" = new."NO MATRIK";

  if not found then
    raise exception 'No stud_xp row found for NO MATRIK %', new."NO MATRIK";
  end if;
  return new;
end;
$$;

drop trigger if exists on_xp_event_created on public.xp_events;
create trigger on_xp_event_created
after insert on public.xp_events
for each row execute procedure public.apply_xp_event();

-- Lecturer/admin award for consultation, participation, discipline, etc.
create or replace function public.award_manual_xp(
  p_no_matrik text,
  p_rule_code text,
  p_reason text,
  p_points_override integer default null,
  p_reference text default null
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_id bigint;
  v_points integer;
begin
  if coalesce(public.current_role(), '') not in ('lecturer','admin') then
    raise exception 'Only lecturers and administrators can award XP';
  end if;

  if not exists (
    select 1 from public.profiles
    where "NO MATRIK" = p_no_matrik and role = 'student'
  ) then
    raise exception 'No student profile found for NO MATRIK %', p_no_matrik;
  end if;

  select coalesce(p_points_override, default_points)
  into v_points
  from public.xp_rules
  where code = p_rule_code and award_mode = 'manual' and active;

  if v_points is null or v_points <= 0 or v_points > 1000 then
    raise exception 'Invalid or inactive manual XP rule/points';
  end if;

  insert into public.xp_events (
    "NO MATRIK", rule_code, points, source_id, reason, award_mode, awarded_by
  )
  values (
    p_no_matrik,
    p_rule_code,
    v_points,
    coalesce(nullif(p_reference, ''), gen_random_uuid()::text),
    p_reason,
    'manual',
    auth.uid()
  )
  returning id into v_event_id;

  return v_event_id;
end;
$$;

revoke all on function public.award_manual_xp(text, text, text, integer, text) from public;
revoke execute on function public.award_manual_xp(text, text, text, integer, text) from anon;
grant execute on function public.award_manual_xp(text, text, text, integer, text) to authenticated;

-- Automatic award for the first authenticated student who has a valid
-- submission for an assignment. Repeated calls are idempotent.
create or replace function public.award_earliest_submission_xp(
  p_assignment_id bigint
) returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_no_matrik text;
  v_first_user uuid;
  v_points integer;
  v_inserted integer := 0;
begin
  select "NO MATRIK" into v_no_matrik
  from public.profiles
  where id = auth.uid() and role = 'student';

  if v_no_matrik is null then
    raise exception 'A linked student profile is required';
  end if;

  select student_user_id into v_first_user
  from public.submissions
  where assignment_id = p_assignment_id
    and status in ('Submitted','Graded')
  order by submitted_at asc, id asc
  limit 1;

  if v_first_user is distinct from auth.uid() then
    return 0;
  end if;

  select default_points into v_points
  from public.xp_rules
  where code = 'earliest_submission' and award_mode = 'automatic' and active;

  if v_points is null then
    return 0;
  end if;

  insert into public.xp_events (
    "NO MATRIK", rule_code, points, source_id, reason, award_mode, awarded_by
  )
  values (
    v_no_matrik,
    'earliest_submission',
    v_points,
    p_assignment_id::text,
    'First valid assignment submission',
    'automatic',
    null
  )
  on conflict ("NO MATRIK", rule_code, source_id) do nothing;

  get diagnostics v_inserted = row_count;
  return case when v_inserted = 1 then v_points else 0 end;
end;
$$;

revoke all on function public.award_earliest_submission_xp(bigint) from public;
revoke execute on function public.award_earliest_submission_xp(bigint) from anon;
grant execute on function public.award_earliest_submission_xp(bigint) to authenticated;

drop policy if exists "profiles_read" on public.profiles;
