-- XPLMS database extension
-- Run once in the Supabase SQL Editor. Existing stud_background and
-- stud_progress tables are intentionally not modified.
--
-- Student identity model:
--   "NO MATRIK"     = institutional student identifier shared by
--                     stud_background and stud_progress.
--   id/user UUID    = Supabase Auth identifier used only for authentication
--                     and row-level security.

create extension if not exists "pgcrypto";

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'student' check (role in ('student','lecturer','admin')),
  "NO MATRIK" text unique,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role, "NO MATRIK")
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    case when new.raw_user_meta_data->>'role' in ('student','lecturer','admin')
      then new.raw_user_meta_data->>'role' else 'student' end,
    coalesce(
      new.raw_user_meta_data->>'NO MATRIK',
      new.raw_user_meta_data->>'no_matrik'
    )
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users for each row execute procedure public.handle_new_user();

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  title text not null,
  course text not null,
  instructions text,
  due_date date not null,
  xp_reward integer not null default 0 check (xp_reward >= 0),
  status text not null default 'Open',
  lecturer_id uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  student_user_id uuid not null references auth.users(id) on delete cascade,
  "NO MATRIK" text not null references public.profiles("NO MATRIK") on update cascade,
  file_path text not null,
  return_file_path text,
  note text,
  score numeric(5,2) check (score between 0 and 100),
  grade text,
  feedback text,
  status text not null default 'Submitted',
  submitted_at timestamptz not null default now(),
  graded_at timestamptz,
  unique (assignment_id, "NO MATRIK")
);

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  title text not null,
  course text not null,
  chapter integer check (chapter in (1, 2, 5, 8, 9, 10)),
  material_type text check (
    material_type in ('Infographic','Notes','Exercise','Extra','Reference','Other')
  ),
  type text,
  file_path text not null,
  lecturer_id uuid references auth.users(id),
  uploaded_at timestamptz not null default now()
);

-- Configurable XP catalogue. Manual rules are awarded by lecturers/admins;
-- automatic rules are awarded only by dedicated, server-verified functions.
create table if not exists public.xp_rules (
  code text primary key,
  name text not null,
  description text not null,
  award_mode text not null check (award_mode in ('manual','automatic')),
  default_points integer not null check (default_points > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.xp_rules (code, name, description, award_mode, default_points)
values
  ('consultation', 'Consultation', 'Constructive academic consultation outside normal class activity.', 'manual', 20),
  ('class_participation', 'Class participation', 'Meaningful contribution during a class session.', 'manual', 10),
  ('discipline', 'Discipline and professionalism', 'Consistent discipline, punctuality or professional conduct.', 'manual', 10),
  ('quiz_completion', 'In-app quiz', 'Successfully completed in-app quiz.', 'automatic', 25),
  ('earliest_submission', 'Earliest valid submission', 'First valid submission received for an assignment.', 'automatic', 30)
on conflict (code) do nothing;

-- Immutable XP ledger. stud_xp."XP" is the current balance; every ledger
-- entry explains one change and prevents the same automatic award recurring.
create table if not exists public.xp_events (
  id bigint generated by default as identity primary key,
  "NO MATRIK" text not null references public.profiles("NO MATRIK") on update cascade,
  rule_code text not null references public.xp_rules(code),
  points integer not null check (points <> 0),
  source_id text not null,
  reason text not null,
  award_mode text not null check (award_mode in ('manual','automatic','adjustment')),
  awarded_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique ("NO MATRIK", rule_code, source_id)
);

insert into storage.buckets (id, name, public)
values ('submissions', 'submissions', false), ('materials', 'materials', false)
on conflict (id) do nothing;

